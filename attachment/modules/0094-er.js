
function er(c, t, e, s, i) {
  let n;
  (c
    ? (c < 0 && ((n = i[0]), (i[0] = i[2]), (i[2] = n)),
      (i[0] *= c),
      (i[2] *= c),
      t < 0 && ((n = i[1]), (i[1] = i[3]), (i[3] = n)),
      (i[1] *= t),
      (i[3] *= t))
    : i.fill(0),
    (i[0] += e),
    (i[1] += s),
    (i[2] += e),
    (i[3] += s));
}